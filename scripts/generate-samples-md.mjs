#!/usr/bin/env node
/*
 * Generates SAMPLES.md - the catalogue you can read without an SAP system.
 *
 * Why it exists: the overview app (z2ui5_cl_smp_app_000) is the catalogue, and
 * reaching it costs an installed framework, an abapGit pull and an HTTP
 * handler. Until then this repository is a flat folder of 150 classes whose
 * names encode nothing, so the one question a visitor arrives with - "is there
 * a sample for X?" - has no answer on GitHub. Worse, everything under src/00
 * has no overview app at all (AGENTS.md section 3): those 49 apps are
 * reachable by class name only, and nothing anywhere lists the names.
 *
 * So this writes the same catalogue as markdown: every sample, its
 * description, its search keywords - which the app keeps for its search box
 * and which are exactly what a reader searches this page for - and a link to
 * the source. Generated from the same scan as the overview app
 * (scripts/lib/scan-samples.mjs), so the two can never disagree.
 *
 * Not hand-maintained, and not meant to be: it is regenerated by
 * `npm run launchpad` together with the overview app, and the
 * publish-overview-apps workflow pushes the result onto a pull request that
 * left it stale.
 *
 * No dependencies. Run:  node scripts/generate-samples-md.mjs
 */
import fs from 'fs';
import path from 'path';
import { ROOT, DOCS_SITE, scanSamples } from './lib/scan-samples.mjs';

const OUT = path.join(ROOT, 'SAMPLES.md');

/* `--check` renders the same page and compares it instead of writing it, so
 * `npm run check` can hold what the publish-overview-apps workflow holds
 * without rewriting the tree while it does so. Same code path, one branch at
 * the end. */
const CHECK = process.argv.includes('--check');

// A table cell ends at an unescaped pipe, and a < starts raw HTML on GitHub.
// The DESCRIPT texts are free text maintained on the classes, so neither is
// ours to rule out - a backtick is the only character the scan refuses.
const cell = (s) =>
  s.replace(/\|/g, '\\|').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// GitHub's heading anchors: lower case, spaces to hyphens, everything that is
// not a word character or a hyphen dropped.
const anchor = (title) =>
  title.toLowerCase().replace(/[^\w\- ]/g, '').replace(/ /g, '-');

/**
 * One table row: what the sample shows, and the class to run and to read.
 *
 * `underHeading` drops a header that only repeats the section it sits under -
 * a "Popover" column under a "Popover" heading, six times. A numbered series
 * keeps its header, because there the numeral is the reading order.
 */
function row(tile, underHeading) {
  const repeats = underHeading && tile.header === tile.base;
  const title = repeats
    ? cell(tile.sub) || `**${cell(tile.header)}**`
    : tile.sub
      ? `**${cell(tile.header)}** — ${cell(tile.sub)}`
      : `**${cell(tile.header)}**`;
  // What the sample SHOWS, in the author's one sentence (AGENTS.md section 4).
  // It goes directly under the title, in normal type: the title says which
  // sample this is and the keywords say how to find it, but only this line
  // answers the question a reader scanning 97 rows actually has - is this the
  // one I want. Everything below it is metadata; this is the row's content.
  const says = tile.summary ? `<br>${cell(tile.summary)}` : '';
  // The keywords are the app's search terms (AGENTS.md section 4). The app
  // never renders them; here the page IS the search box, so they belong in it -
  // quietly, in the small type the summary line of a row deserves.
  const terms = tile.keywords ? `<br><sub>${cell(tile.keywords)}</sub>` : '';
  // A sample shows HOW; the documentation says WHY and when. Where a chapter
  // exists, the reader of this page should not have to go looking for it - the
  // two were written about the same thing.
  const chapters = tile.docs.length
    ? `<br><sub>docs: ${tile.docs.map((u) => `[${u.replace(DOCS_SITE, '')}](${u})`).join(', ')}</sub>`
    : '';
  const source = `${tile.path}/${tile.app}.clas.abap`;
  return `| ${title}${says}${terms}${chapters} | [\`${tile.app.toUpperCase()}\`](${source}) |`;
}

function table(tiles, underHeading = false) {
  return [
    '| Sample | Class |',
    '|---|---|',
    ...tiles.map((tile) => row(tile, underHeading)),
  ].join('\n');
}

const { areas, hidden } = scanSamples();
const basics = areas['01'];
const system = areas['00'];
const total = basics.length + system.length + hidden.length;

/* How many APPS are here, which is a different question from how many classes
 * match the sample naming scheme: three classes in src/00/98 carry the name and
 * are data objects. The `isApp` flag comes from the source (scan-samples.mjs).
 *
 * PORTABLE is the number the README leads with, and the one worth stating: the
 * apps that survive every build, so they are what a reader gets whichever
 * branch they pull - src/01 plus the overview app itself, which is not a tile
 * and therefore not in the scan. `main` additionally carries src/00, which the
 * 702 downport strips (AGENTS.md section 2). */
const isApp = (t) => t.isApp;
const portable = [...basics, ...hidden].filter((t) => t.area === '01').filter(isApp).length + 1;
const systemApps = [...system, ...hidden].filter((t) => t.area === '00').filter(isApp).length;
const apps = portable + systemApps;
const dataObjects = [...basics, ...system, ...hidden].filter((x) => !isApp(x)).length;

// --- src/01, by category --------------------------------------------------
// The category is the header without its Roman numeral, which is what the
// overview app blocks by too (header_base). The scan already sorted the
// tiles, so first-seen order is catalogue order.
const byCategory = new Map();
for (const tile of basics) {
  if (!byCategory.has(tile.base)) byCategory.set(tile.base, []);
  byCategory.get(tile.base).push(tile);
}

const jumpTo = [...byCategory.keys()]
  .map((name) => `[${name}](#${anchor(name)})`)
  .join(' · ');

const categories = [...byCategory]
  .map(([name, tiles]) => `### ${name}\n\n${table(tiles, true)}`)
  .join('\n\n');

// --- src/00, by subpackage ------------------------------------------------
// One section per subpackage, titled with its CTEXT - these apps are grouped
// by nothing else, and their descriptions do not follow the curated header
// set that src/01 is held to.
const bySubpackage = new Map();
for (const tile of system) {
  const key = `${tile.subnum}|${tile.group}`;
  if (!bySubpackage.has(key)) bySubpackage.set(key, []);
  bySubpackage.get(key).push(tile);
}

const systemSections = [...bySubpackage]
  .map(([key, tiles]) => {
    const [subnum, group] = key.split('|');
    return `### ${group} — \`src/00/${subnum}\`\n\n${tiles.length} app(s).\n\n${table(tiles)}`;
  })
  .join('\n\n');

const page = `<!-- Generated by scripts/generate-samples-md.mjs. Do not edit by hand:
     run \`npm run launchpad\` and commit the result (AGENTS.md section 4). -->

# The sample catalogue

Every app in this repository — ${apps} of them — with what it shows and a link
to its source. This is the [overview app](src/z2ui5_cl_smp_app_000.clas.abap)
as a page you can read here, before installing anything.

**${portable} of them ship on every branch** — the portable set the README counts:
\`src/01\` plus this overview app. The other ${systemApps} are under \`src/00\` and are
stripped from \`702\`. ${dataObjects} further classes carry the sample name and are
data objects the samples share rather than apps; they are listed too, so nothing
in the tree is invisible.

**To run one:** install [abap2UI5](https://github.com/abap2UI5/abap2UI5), pull
this repository with [abapGit](https://abapgit.org), then open
\`<your endpoint>?app_start=<the class in the right-hand column>\`. Or run
\`Z2UI5_CL_SMP_APP_000\` and click through the ${basics.length} samples below —
that is the same list, in the app.

**To read one:** click the class. Every sample is a single class, so the link
is the whole sample.

New to abap2UI5? Start at [Basics](#basics), then the
[documentation](https://abap2ui5.github.io/docs/).

---

## The learning path — \`src/01\`

The ${basics.length} samples the overview app lists: cloud-ready, downportable,
plain OpenUI5 1.71. Each adds one idea. With the ${portable - basics.length - 1}
helper apps they call and the overview app itself, that is the **${portable}
ready-to-run apps** the README leads with.

${jumpTo}

${categories}

---

## Not in any overview — \`src/00\`

${system.length} apps with no tile anywhere (AGENTS.md section 3) — reachable
by class name only, which is what this section is for. They are held to a
lower bar than \`src/01\`: an experimental sample may use something newer than
UI5 1.71, and a testing app exists to be run by a check, not to be learned
from. Both packages are **stripped from the \`702\` branch**, so this section
is absent there.

${systemSections}

---

## Helper apps

${hidden.length} classes that are only ever *called* by another sample — a
sub-app, a data object, the other half of a navigation demo. Their short text
starts with \`ZZZ\`, which is how the generator knows to give them no tile.
Listed here so nothing in the tree is invisible; there is no point starting
one on its own.

${table(hidden)}

---

*Generated from the folder tree and the classes' abapGit short texts by
[\`scripts/generate-samples-md.mjs\`](scripts/generate-samples-md.mjs), which
reads the same scan as the overview app. To change a description, change the
\`<DESCRIPT>\` of the class and run \`npm run launchpad\`.*
`;

// Two things regeneration alone would never catch, because a wrong link is
// reproduced as faithfully as a right one: a source link that points at
// nothing, and a sample that fell out between the scan and the rendering.
for (const tile of [...basics, ...system, ...hidden]) {
  const source = path.join(ROOT, tile.path, `${tile.app}.clas.abap`);
  if (!fs.existsSync(source)) throw new Error(`link would 404: ${tile.path}/${tile.app}.clas.abap`);
  if (!page.includes(`${tile.path}/${tile.app}.clas.abap`)) {
    throw new Error(`${tile.app} was scanned but is in no section of SAMPLES.md`);
  }
}

/* The README leads with the same number, and it is hand-written - so it is the
 * one figure in this repository that can go stale by somebody adding a sample.
 * It said "150+ ready-to-run apps" for a long time, which was a different count
 * of a different thing than any number on this page.
 *
 * Regenerating cannot fix a file it does not write, so it fails instead and
 * says what to put there. Cheap, and it is the front page. */
const README = path.join(ROOT, 'README.md');
const claim = /(\d+) ready-to-run apps/.exec(fs.readFileSync(README, 'utf8'));
if (!claim) {
  throw new Error('README.md no longer states "<n> ready-to-run apps" — this generator counts them, keep the phrase');
}
if (Number(claim[1]) !== portable) {
  throw new Error(
    `README.md says ${claim[1]} ready-to-run apps, the tree holds ${portable} `
    + '(src/01 plus the overview app, the set that survives every build) — fix the README',
  );
}

const counts = `${portable} portable + ${systemApps} system apps (${basics.length} in src/01, ${system.length} in src/00, ${hidden.length} helpers)`;

if (!CHECK) {
  fs.writeFileSync(OUT, page);
  console.log(`SAMPLES.md: ${counts}`);
} else if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== page) {
  console.error('SAMPLES.md no longer mirrors the folder tree.');
  console.error('\nRun `npm run launchpad` and commit the result (AGENTS.md section 3).');
  process.exit(1);
} else {
  console.log(`samples-md: up to date — ${counts}`);
}
