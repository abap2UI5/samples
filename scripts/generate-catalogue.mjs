#!/usr/bin/env node
/*
 * generate-catalogue - the committed, machine-readable index of src/01.
 *
 * The fourth view of the one catalogue, and the first one addressed to a
 * MACHINE. The overview app needs an installed system, SAMPLES.md is markdown
 * a human scrolls, and web/apps.json exists only after a deploy build - so an
 * AI agent that has just cloned this repository (or fetched one raw URL) has
 * no structured answer to "what is in here": only the @keywords/@summary
 * comments spread over 100+ classes, and a markdown table it has to parse
 * with a regex. catalogue.json is that answer as data: one entry per src/01
 * sample with its class, folder, category, learning-path stage, keywords,
 * summary and documentation links, plus a header that says which repository
 * this is, where it stands in the three-repository family, and why a sample
 * NUMBER alone names nothing (the class prefix does).
 *
 * COMMITTED, unlike web/apps.json - and that is not an inconsistency. Both
 * are generated from the same scan, but apps.json is the overview PAGE's
 * build output: its reader always arrives through a deploy that has just
 * regenerated it, so committing it would only add a derived diff to every
 * sample pull request. catalogue.json's reader is a clone or a raw fetch,
 * which no deploy ever runs for - a file that only exists after a build step
 * does not exist for them at all. What keeps a committed derived file honest
 * is the freshness gate below, the same way SAMPLES.md is kept honest.
 *
 * Regenerated by `npm run launchpad` along with the overview app and
 * SAMPLES.md, and pushed by the publish-overview-apps workflow with them.
 *
 *   node scripts/generate-catalogue.mjs           write catalogue.json
 *   node scripts/generate-catalogue.mjs --check   fail when it is stale
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { ROOT, scanSamples } from './lib/scan-samples.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(ROOT, 'catalogue.json');
const CHECK = process.argv.includes('--check');

const { areas } = scanSamples();
const tiles = areas['01'];

/* The teaching order, from the one editorial file behind the overview page
 * (see learning-path.json's own comment). check:overview already holds that
 * every category has exactly one stage; this only reads the mapping. */
const { stages } = JSON.parse(
  fs.readFileSync(path.join(HERE, 'lib', 'learning-path.json'), 'utf8'),
);
const stageOf = new Map();
for (const stage of stages) {
  for (const name of stage.categories) stageOf.set(name, stage.id);
}
for (const tile of tiles) {
  if (!stageOf.has(tile.base)) {
    console.error(`category "${tile.base}" belongs to no stage of the learning path - `
      + 'fix scripts/lib/learning-path.json first (npm run check:overview says the same)');
    process.exit(1);
  }
}

const data = {
  purpose: 'Machine-readable catalogue of the abap2UI5 samples in this repository, '
    + 'for AI tooling and other programs. Humans read SAMPLES.md - the same catalogue '
    + 'rendered as a page. Generated by scripts/generate-catalogue.mjs from the one scan '
    + 'behind every view of the catalogue (scripts/lib/scan-samples.mjs); '
    + 'regenerate with `npm run catalogue`, never edit by hand.',
  repository: 'abap2UI5/samples',
  role: 'Step 1 of the three abap2UI5 sample repositories: the learning path - '
    + 'bindings, events, popups, navigation, complete apps. '
    + 'Step 2 is samples-controls (the UI5 demo kit rebuilt, one port per control sample), '
    + 'step 3 is samples-stack (everything that needs the system: OData, RAP, WebSockets, the Fiori Launchpad).',
  family: [
    { repository: 'abap2UI5/samples', classPrefix: 'z2ui5_cl_smp_app_', overviewApp: 'z2ui5_cl_smp_app_000' },
    { repository: 'abap2UI5/samples-controls', classPrefix: 'z2ui5_cl_smpc_app_', overviewApp: 'z2ui5_cl_smpc_app_000' },
    { repository: 'abap2UI5/samples-stack', classPrefix: 'z2ui5_cl_smps_app_', overviewApp: 'z2ui5_cl_smps_app_000' },
  ],
  naming: {
    caveat: 'Sample numbers are handed out per repository, and the three repositories reuse '
      + 'each other\'s numbers freely - there is no global number space. A number alone therefore '
      + 'names nothing: the class prefix is what says which repository\'s sample you mean. '
      + 'Always use the full class name.',
    example: 'z2ui5_cl_smp_app_493 (here: Hello World) and z2ui5_cl_smps_app_493 '
      + '(samples-stack: a FilterBar with variant management) share the number 493 and have nothing to do with each other.',
  },
  scope: 'One entry per sample in src/01 - the portable set every branch and build ships. '
    + 'The src/00 system area (experimental and testing apps, stripped from the 702 branch) '
    + 'and the hidden ZZZ helper classes are listed in SAMPLES.md only.',
  learningPath: stages.map(({ id, title, blurb }) => ({ id, title, blurb })),
  counts: {
    samples: tiles.length,
    categories: new Set(tiles.map((t) => t.base)).size,
    stages: stages.length,
  },
  samples: tiles.map((tile) => ({
    class: tile.app,
    file: `${tile.path}/${tile.app}.clas.abap`,
    category: tile.base,
    stage: stageOf.get(tile.base),
    title: tile.header,
    description: tile.sub,
    summary: tile.summary,
    keywords: tile.keywords ? tile.keywords.split(/\s+/) : [],
    docs: tile.docs,
  })),
};

const page = `${JSON.stringify(data, null, 1)}\n`;

if (!CHECK) {
  fs.writeFileSync(OUT, page);
  console.log(`catalogue.json: ${data.counts.samples} samples · ${data.counts.categories} categories · ${data.counts.stages} stages`);
} else if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== page) {
  console.error('catalogue.json no longer mirrors the folder tree.');
  console.error('\nRun `npm run launchpad` and commit the result (AGENTS.md section 3).');
  process.exit(1);
} else {
  console.log(`catalogue: up to date — ${data.counts.samples} samples · ${data.counts.categories} categories · ${data.counts.stages} stages`);
}
